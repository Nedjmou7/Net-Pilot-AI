import ipaddress
import re
from typing import Dict, List, Tuple
from backend.models import Topology, Device, Link, IpPlanItem


def ip_to_wildcard(netmask_str: str) -> str:
    """Convert dotted subnet mask (e.g. 255.255.255.0) to wildcard mask (0.0.0.255)."""
    try:
        octets = [int(x) for x in netmask_str.split(".")]
        wildcards = [255 - o for o in octets]
        return ".".join(str(w) for w in wildcards)
    except Exception:
        return "0.0.0.255"


def generate_ios_configs(topology: Topology) -> Dict[str, str]:
    """Generate clean, standard Cisco IOS CLI configuration for every device in topology."""
    configs: Dict[str, str] = {}
    device_map: Dict[str, Device] = {d.id: d for d in topology.devices}

    # Identify trunk links (router with subinterfaces to switch, or switch to switch)
    trunk_ports: Dict[str, List[str]] = {d.id: [] for d in topology.devices}
    access_ports: Dict[str, List[Tuple[str, int]]] = {d.id: [] for d in topology.devices}

    has_subinterfaces = any("." in item.interface for item in topology.ip_plan)

    for link in topology.links:
        dev_a = device_map.get(link.a)
        dev_b = device_map.get(link.b)
        if not dev_a or not dev_b:
            continue

        if dev_a.type == "switch" and dev_b.type == "switch":
            trunk_ports[dev_a.id].append(link.a_port)
            trunk_ports[dev_b.id].append(link.b_port)
        elif dev_a.type == "switch" and dev_b.type == "router" and has_subinterfaces:
            trunk_ports[dev_a.id].append(link.a_port)
        elif dev_b.type == "switch" and dev_a.type == "router" and has_subinterfaces:
            trunk_ports[dev_b.id].append(link.b_port)
        elif dev_a.type == "switch" and dev_b.type in ("pc", "server"):
            # Determine if PC has a VLAN
            access_ports[dev_a.id].append((link.a_port, 1))
        elif dev_b.type == "switch" and dev_a.type in ("pc", "server"):
            access_ports[dev_b.id].append((link.b_port, 1))

    # Map VLANs by PC subnet if available
    vlan_subnets = {}
    for item in topology.ip_plan:
        if "." in item.interface:
            try:
                vlan_id = int(item.interface.split(".")[1])
                net = ipaddress.IPv4Network(f"{item.ip}/{item.mask}", strict=False)
                vlan_subnets[str(net)] = vlan_id
            except Exception:
                pass

    for dev in topology.devices:
        lines: List[str] = [
            f"! Configuration for {dev.id} ({dev.model})",
            "! Generated by TopoGemma / Net-Pilot-AI",
            "enable",
            "configure terminal",
            f"hostname {dev.id}",
            "no ip domain-lookup",
            "line console 0",
            " logging synchronous",
            " exec-timeout 0 0",
            " exit"
        ]

        dev_ips = [item for item in topology.ip_plan if item.device == dev.id]

        if dev.type == "router":
            # Group interfaces (base and subinterfaces)
            base_interfaces_seen = set()
            subinterfaces_by_base: Dict[str, List[IpPlanItem]] = {}
            standard_interfaces: List[IpPlanItem] = []

            for ip_item in dev_ips:
                if "." in ip_item.interface:
                    base = ip_item.interface.split(".")[0]
                    if base not in subinterfaces_by_base:
                        subinterfaces_by_base[base] = []
                    subinterfaces_by_base[base].append(ip_item)
                else:
                    standard_interfaces.append(ip_item)

            # Standard interfaces
            for item in standard_interfaces:
                lines.append(f"interface {item.interface}")
                lines.append(f" ip address {item.ip} {item.mask}")
                lines.append(" no shutdown")
                lines.append(" exit")

            # Subinterfaces (Router on a stick)
            for base, sub_list in subinterfaces_by_base.items():
                lines.append(f"interface {base}")
                lines.append(" no ip address")
                lines.append(" no shutdown")
                lines.append(" exit")
                for sub in sub_list:
                    sub_vlan = sub.interface.split(".")[1]
                    lines.append(f"interface {sub.interface}")
                    lines.append(f" encapsulation dot1Q {sub_vlan}")
                    lines.append(f" ip address {sub.ip} {sub.mask}")
                    lines.append(" no shutdown")
                    lines.append(" exit")

            # DHCP pools
            if topology.services.dhcp:
                router_ips = {
                    item.ip
                    for item in dev_ips
                    if item.interface.split(".")[0] in {
                        link.a_port if link.a == dev.id else link.b_port
                        for link in topology.links
                        if link.a == dev.id or link.b == dev.id
                    }
                }
                for pool in topology.services.dhcp:
                    if pool.default_router not in router_ips:
                        continue
                    lines.append(f"ip dhcp excluded-address {pool.default_router}")
                    lines.append(f"ip dhcp pool {pool.pool_name}")
                    lines.append(f" network {pool.network} {pool.mask}")
                    lines.append(f" default-router {pool.default_router}")
                    if pool.dns_server:
                        lines.append(f" dns-server {pool.dns_server}")
                    lines.append(" exit")

            # Routing
            routing = topology.routing
            protocol = routing.protocol.strip().lower()
            if protocol == "ospf":
                pid = routing.process_id or 1
                area = routing.area if routing.area is not None else 0
                lines.append(f"router ospf {pid}")
                for item in dev_ips:
                    try:
                        net = ipaddress.IPv4Network(f"{item.ip}/{item.mask}", strict=False)
                        wildcard = ip_to_wildcard(item.mask)
                        lines.append(f" network {net.network_address} {wildcard} area {area}")
                    except Exception:
                        pass
                lines.append(" exit")
            elif protocol == "rip":
                lines.append("router rip")
                lines.append(" version 2")
                lines.append(" no auto-summary")
                for item in dev_ips:
                    try:
                        net = ipaddress.IPv4Network(f"{item.ip}/{item.mask}", strict=False)
                        lines.append(f" network {net.network_address}")
                    except Exception:
                        pass
                lines.append(" exit")
            elif protocol == "static":
                # Add sample static route pointing to remote subnets
                lines.append("! Static route template: ip route <dest_net> <mask> <next_hop>")
            elif protocol != "none":
                lines.append(
                    f"! Requested routing protocol: {routing.protocol}. "
                    "Protocol-specific commands must be reviewed and completed for this IOS image."
                )

            # NAT
            if topology.services.nat:
                nat = topology.services.nat
                for inside_if in nat.inside_interfaces:
                    lines.append(f"interface {inside_if}")
                    lines.append(" ip nat inside")
                    lines.append(" exit")
                if nat.outside_interface:
                    lines.append(f"interface {nat.outside_interface}")
                    lines.append(" ip nat outside")
                    lines.append(" exit")
                lines.append("access-list 1 permit any")
                lines.append(f"ip nat inside source list 1 interface {nat.outside_interface} overload")

            # ACLs
            for acl in topology.services.acls:
                if acl.type == "standard":
                    lines.append(f"access-list {acl.id} {acl.action} {acl.source}")
                else:
                    proto = acl.protocol or "ip"
                    dest = acl.destination or "any"
                    lines.append(f"access-list {acl.id} {acl.action} {proto} {acl.source} {dest}")

        elif dev.type == "switch":
            # VLAN creation
            if topology.vlans:
                for v in topology.vlans:
                    lines.append(f"vlan {v.id}")
                    lines.append(f" name {v.name}")
                    lines.append(" exit")

            # Trunk ports
            for t_port in trunk_ports[dev.id]:
                lines.append(f"interface {t_port}")
                if "3650" in dev.model:
                    lines.append(" switchport trunk encapsulation dot1q")
                lines.append(" switchport mode trunk")
                lines.append(" switchport trunk allowed vlan all")
                lines.append(" no shutdown")
                lines.append(" exit")

            # Access ports
            for a_port, default_vlan in access_ports[dev.id]:
                lines.append(f"interface {a_port}")
                lines.append(" switchport mode access")
                if topology.vlans:
                    lines.append(f" switchport access vlan {topology.vlans[0].id}")
                lines.append(" no shutdown")
                lines.append(" exit")

            # Management SVI
            for item in dev_ips:
                lines.append(f"interface {item.interface}")
                lines.append(f" ip address {item.ip} {item.mask}")
                lines.append(" no shutdown")
                lines.append(" exit")
                if item.gateway:
                    lines.append(f"ip default-gateway {item.gateway}")

        elif dev.type in ("pc", "server"):
            lines.append(f"! Host IP Configuration for {dev.id}")
            for item in dev_ips:
                lines.append(f"! IP: {item.ip}")
                lines.append(f"! Mask: {item.mask}")
                lines.append(f"! Gateway: {item.gateway or 'None'}")

        lines.append("end")
        lines.append("write memory")
        configs[dev.id] = "\n".join(lines)

    return configs


def generate_ptbuilder_script(topology: Topology) -> str:
    """
    Generate JavaScript for the optional external PTBuilder bridge.
    This is not a native Cisco Packet Tracer .pkt file or built-in Packet Tracer script.
    Follows PTBuilder API signatures:
    - addDevice(name, model, x, y)
    - addLink(dev1, port1, dev2, port2, cable)
    - configureIosDevice(name, config)
    - configurePcIp(name, dhcp, ip, mask, gateway)
    """
    configs = generate_ios_configs(topology)
    ip_map = {item.device: item for item in topology.ip_plan}

    lines = [
        "// TopoGemma / Net-Pilot-AI Automated Packet Tracer Build Script",
        f"// Project: {topology.name}",
        "// Generated dynamically from validated network topology",
        "",
        "function main() {",
        "    var banner = 'TopoGemma: Building topology ' + '" + topology.name + "';",
        "    echo(banner);",
        "",
        "    // 1. Create Network Devices"
    ]

    for dev in topology.devices:
        x_val = int(dev.x)
        y_val = int(dev.y)
        lines.append(f'    addDevice("{dev.id}", "{dev.model}", {x_val}, {y_val});')

    lines.append("")
    lines.append("    // 2. Create Physical Links and Cables")
    for link in topology.links:
        cable_type = link.cable or "straight"
        lines.append(f'    addLink("{link.a}", "{link.a_port}", "{link.b}", "{link.b_port}", "{cable_type}");')

    lines.append("")
    lines.append("    // 3. Configure End Host IP Settings")
    use_dhcp = bool(topology.services.dhcp)
    for dev in topology.devices:
        if dev.type in ("pc", "server"):
            ip_info = ip_map.get(dev.id)
            if use_dhcp:
                lines.append(f'    configurePcIp("{dev.id}", true, "", "", "");')
            elif ip_info:
                gw_val = ip_info.gateway if ip_info.gateway else ""
                lines.append(f'    configurePcIp("{dev.id}", false, "{ip_info.ip}", "{ip_info.mask}", "{gw_val}");')
            else:
                lines.append(f'    configurePcIp("{dev.id}", true, "", "", "");')

    lines.append("")
    lines.append("    // 4. Push Cisco IOS Device Configurations")
    for dev in topology.devices:
        if dev.type in ("router", "switch"):
            cfg = configs.get(dev.id, "")
            # Escape newlines and quotes for JS string
            escaped_cfg = cfg.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n")
            lines.append(f'    configureIosDevice("{dev.id}", "{escaped_cfg}");')

    lines.append("")
    lines.append("    echo('TopoGemma: Packet Tracer Topology successfully deployed!');")
    lines.append("}")
    lines.append("")
    lines.append("main();")

    return "\n".join(lines)


def generate_all_artifacts(topology: Topology) -> Tuple[str, Dict[str, str]]:
    """Return both PTBuilder script and dictionary of IOS CLI configs."""
    configs = generate_ios_configs(topology)
    script = generate_ptbuilder_script(topology)
    return script, configs
